const {JSDOM} = require('../data/qa/node_modules/jsdom');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const source = fs.readFileSync('includes/admin_ai_view.php', 'utf8').replace(/<\?php[\s\S]*?\?>/g, '');
const dom = new JSDOM(`<!doctype html><body>${source}</body>`, {url: 'http://localhost/QuizWeb/admin.php?tab=ai', runScripts: 'outside-only'});
const w = dom.window;
w.eval(fs.readFileSync('assets/js/admin-ai.js', 'utf8'));
const tick = () => new Promise(resolve => setImmediate(resolve));
(async () => {
    const form = w.document.querySelector('[data-ai-remove]');
    const button = form.querySelector('button');
    let submitCount = 0;
    form.requestSubmit = () => { submitCount++; form.dispatchEvent(new w.Event('submit', {cancelable: true})); };
    w.chalkConfirm = async () => false;
    const cancelled = new w.Event('submit', {cancelable: true});
    form.dispatchEvent(cancelled); await tick();
    assert(cancelled.defaultPrevented && submitCount === 0 && !button.disabled);
    w.chalkConfirm = async () => true;
    form.dispatchEvent(new w.Event('submit', {cancelable: true})); await tick();
    assert.equal(submitCount, 1);
    assert(button.disabled, 'Confirmed removal blocks double-submit');
    const duplicate = new w.Event('submit', {cancelable: true});
    form.dispatchEvent(duplicate);
    assert(duplicate.defaultPrevented);
    const test = w.document.querySelector('[name=action][value=ai_test_connection]').form;
    test.dispatchEvent(new w.Event('submit', {cancelable: true}));
    assert.match(test.querySelector('[data-ai-form-status]').textContent, /Checking/);
    const password = w.document.querySelector('[name=api_key]');
    assert.equal(password.type, 'password'); assert.equal(password.value, '');
    dom.window.close();
    console.log('Admin AI UI checks passed: masked input, removal confirmation/cancel, busy state and duplicate-submit protection.');
})().catch(error => { console.error(error); dom.window.close(); process.exitCode = 1; });
