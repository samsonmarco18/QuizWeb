        if (['crossword', 'fill_blank', 'emoji_quiz', 'flip_match'].includes(mode)) assert.equal(imported[0].answer, generated[0].answer, `${mode} expected answer imports`);
        if (mode === 'fill_blank') {
            assert.equal(imported[0].accepted_answers[0], generated[0].accepted_answers[0]);
            assert.equal(imported[0].hint, 'A lesson hint');
        }
