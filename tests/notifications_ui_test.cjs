const { JSDOM } = require('../data/qa/node_modules/jsdom');
const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const php = process.env.PHP_BINARY || 'C:/xampppp/php/php.exe';
const markup = execFileSync(php, ['tests/notifications_test.php', '--html'], { encoding: 'utf8' });
const script = fs.readFileSync('assets/js/notifications.js', 'utf8');
function boot(saved, userId = 7) {
    const dom = new JSDOM(`<button class="account-toggle" aria-expanded="true"></button><div id="account-dropdown"></div>${markup.replace('data-user-id="7"', `data-user-id="${userId}"`)}<button id="outside">Outside</button>`, { url: 'http://localhost/QuizWeb/dashboard.php', runScripts: 'outside-only' });
    if (saved) dom.window.localStorage.setItem('quizweb-notifications-read:7', saved);
    dom.window.eval(script);
    return dom;
}
const dom = boot(), w = dom.window, d = w.document;
const toggle = d.querySelector('.notification-toggle'), panel = d.querySelector('.notification-panel');
const count = d.querySelector('[data-notification-count]');
assert.equal(count.textContent, '2');
toggle.click();
assert.equal(panel.hidden, false);
assert.equal(toggle.getAttribute('aria-expanded'), 'true');
assert.equal(d.getElementById('account-dropdown').hidden, true);
w.innerWidth = 390; w.dispatchEvent(new w.Event('resize'));
assert.notEqual(panel.style.top, '');
w.innerWidth = 1440; w.dispatchEvent(new w.Event('resize'));
assert.equal(panel.style.top, '');
d.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'Escape' }));
assert.equal(panel.hidden, true);
assert.equal(d.activeElement, toggle);
toggle.click(); d.getElementById('outside').click();
assert.equal(panel.hidden, true);
toggle.click(); toggle.dispatchEvent(new w.FocusEvent('focusout', { bubbles: true, relatedTarget: d.getElementById('outside') }));
assert.equal(panel.hidden, true);
const first = d.querySelector('[data-notification-id]');
first.addEventListener('click', event => event.preventDefault()); first.click();
assert.equal(count.textContent, '1');
d.querySelector('[data-notifications-read]').click();
assert.equal(count.hidden, true);
assert.equal(d.querySelector('[data-notifications-read]').disabled, true);
const saved = w.localStorage.getItem('quizweb-notifications-read:7');
const reload = boot(saved), otherUser = boot(saved, 8), malformed = boot('{broken');
assert.equal(reload.window.document.querySelector('[data-notification-count]').hidden, true);
assert.equal(otherUser.window.document.querySelector('[data-notification-count]').textContent, '2');
assert.equal(malformed.window.document.querySelector('[data-notification-count]').textContent, '2');
w.localStorage.removeItem('quizweb-notifications-read:7');
w.dispatchEvent(new w.StorageEvent('storage', { key: 'quizweb-notifications-read:7' }));
assert.equal(count.textContent, '2');
for (const instance of [dom, reload, otherUser, malformed]) instance.window.close();
console.log('Notification badge, read state, account isolation, storage recovery, and keyboard dismissal passed.');
